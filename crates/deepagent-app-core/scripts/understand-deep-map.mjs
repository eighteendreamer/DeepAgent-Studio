#!/usr/bin/env node
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const [,, pluginRootArg, projectRootArg, outputPathArg] = process.argv;
if (!pluginRootArg || !projectRootArg || !outputPathArg) {
  process.stderr.write("Usage: node understand-deep-map.mjs <pluginRoot> <projectRoot> <outputPath>\n");
  process.exit(2);
}

const pluginRoot = resolve(pluginRootArg);
const projectRoot = resolve(projectRootArg);
const outputPath = resolve(outputPathArg);
const ignoredDirNames = new Set([
  ".git",
  ".idea",
  ".vscode",
  ".deepagent",
  ".understand-anything",
  "node_modules",
  "target",
  "dist",
  "build",
  "out",
  ".next",
  ".nuxt",
  ".turbo",
  ".cache",
  "coverage",
  "vendor",
  "venv",
  ".venv",
  "__pycache__",
]);

const coreDist = join(pluginRoot, "packages", "core", "dist", "index.js");
if (!existsSync(coreDist)) {
  process.stderr.write(`Understand-Anything core is not built: ${coreDist}\n`);
  process.exit(3);
}

const core = await import(pathToFileURL(coreDist).href);
const {
  TreeSitterPlugin,
  PluginRegistry,
  GraphBuilder,
  builtinLanguageConfigs,
  registerAllParsers,
  createIgnoreFilter,
  sanitizeGraph,
  autoFixGraph,
  validateGraph,
} = core;

const gitHash = spawnSync("git", ["-C", projectRoot, "rev-parse", "HEAD"], {
  encoding: "utf-8",
  windowsHide: true,
}).stdout.trim() || "";

const registry = new PluginRegistry();
const treeSitterPlugin = new TreeSitterPlugin(builtinLanguageConfigs.filter((config) => config.treeSitter));
await treeSitterPlugin.init();
registry.register(treeSitterPlugin);
registerAllParsers(registry);

const ignore = createIgnoreFilter(projectRoot);
const files = [];
walk(projectRoot, "");
files.sort((a, b) => sourceRank(a) - sourceRank(b) || a.localeCompare(b));

const builder = new GraphBuilder(basename(projectRoot), gitHash);
const fileSet = new Set(files);
const callEdges = [];
const importEdges = [];

for (const file of files) {
  const abs = join(projectRoot, file);
  let content;
  try {
    content = readFileSync(abs, "utf-8");
  } catch {
    continue;
  }
  const language = registry.getLanguageForFile(file) ?? "unknown";
  const lines = content.split(/\r?\n/).length;
  const complexity = lines >= 500 ? "complex" : lines >= 150 ? "moderate" : "simple";
  const tags = [language, categoryFor(file, language)].filter(Boolean);
  const analysis = safe(() => registry.analyzeFile(file, content));
  const meta = {
    summary: `${language} file, ${lines} lines. Generated by Understand-Anything deep map.`,
    fileSummary: `${language} file, ${lines} lines. Generated by Understand-Anything deep map.`,
    tags,
    complexity,
    summaries: {},
  };

  if (analysis && hasStructure(analysis)) {
    builder.addFileWithAnalysis(file, analysis, meta);
  } else if (analysis && hasNonCodeStructure(analysis)) {
    builder.addNonCodeFileWithAnalysis(file, {
      nodeType: nodeTypeFor(file, language),
      summary: meta.summary,
      tags,
      complexity,
      definitions: analysis.definitions,
      services: analysis.services,
      endpoints: analysis.endpoints,
      steps: analysis.steps,
      resources: analysis.resources,
      sections: analysis.sections,
    });
  } else {
    builder.addFile(file, meta);
  }

  for (const target of resolveImports(file, analysis?.imports ?? [], fileSet)) {
    importEdges.push([file, target]);
  }

  const cg = safe(() => registry.extractCallGraph(file, content)) ?? [];
  for (const entry of cg) {
    if (entry?.caller && entry?.callee) {
      callEdges.push([file, entry.caller, file, entry.callee]);
    }
  }
}

for (const [from, to] of importEdges) {
  builder.addImportEdge(from, to);
}
for (const [callerFile, caller, calleeFile, callee] of callEdges) {
  builder.addCallEdge(callerFile, caller, calleeFile, callee);
}

let graph = builder.build();
graph.kind = "codebase";
graph.project.description = "Understand-Anything deep project map generated inside DeepAgent.";
graph.project.frameworks = detectFrameworks();
const nodeIds = new Set(graph.nodes.map((node) => node.id));
graph.edges = graph.edges.filter((edge) => nodeIds.has(edge.source) && nodeIds.has(edge.target));
graph = sanitizeGraph ? sanitizeGraph(graph) : graph;
graph = autoFixGraph ? autoFixGraph(graph).data : graph;
const validation = validateGraph ? validateGraph(graph) : { valid: true };
const blockingIssues = (validation.issues ?? []).filter((issue) => issue.level !== "auto-corrected");
if (blockingIssues.length > 0) {
  process.stderr.write(`Warning: Understand-Anything graph validation reported ${blockingIssues.length} non-auto-corrected issue(s).\n`);
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, JSON.stringify(graph, null, 2), "utf-8");
process.stdout.write(JSON.stringify({
  ok: true,
  outputPath,
  files: files.length,
  nodes: graph.nodes.length,
  edges: graph.edges.length,
  languages: graph.project.languages,
  frameworks: graph.project.frameworks,
}));

function walk(absDir, relDir) {
  let entries;
  try {
    entries = readdirSync(absDir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  } catch {
    return;
  }
  for (const entry of entries) {
    const relPath = relDir ? `${relDir}/${entry.name}` : entry.name;
    if (shouldSkipGeneratedPath(relPath)) continue;
    if (ignore.isIgnored(relPath) || ignore.isIgnored(`${relPath}/`)) continue;
    const absPath = join(absDir, entry.name);
    if (entry.isDirectory()) {
      walk(absPath, relPath);
      continue;
    }
    if (!entry.isFile()) continue;
    if (isBinaryLike(entry.name)) continue;
    try {
      if (statSync(absPath).size > 1_500_000) continue;
    } catch {
      continue;
    }
    const language = registry.getLanguageForFile(relPath);
    if (language || isKnownPlainFile(entry.name)) {
      files.push(toPosix(relative(projectRoot, absPath)));
    }
  }
}

function shouldSkipGeneratedPath(relPath) {
  return relPath
    .split("/")
    .some((part) => ignoredDirNames.has(part));
}

function resolveImports(file, imports, fileSet) {
  const out = new Set();
  const dir = dirname(file).replace(/\\/g, "/");
  for (const imp of imports) {
    const source = imp?.source;
    if (!source || typeof source !== "string") continue;
    if (source.startsWith(".") || source.startsWith("/")) {
      const base = normalizePath(`${dir}/${source}`);
      for (const target of candidatePaths(base)) {
        if (fileSet.has(target)) {
          out.add(target);
          break;
        }
      }
    } else {
      const javaPath = `${source.replace(/\./g, "/")}.java`;
      for (const target of fileSet) {
        if (target.endsWith(javaPath)) out.add(target);
      }
    }
  }
  return [...out].filter((target) => target !== file);
}

function candidatePaths(base) {
  const extensions = ["", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".json", ".java", ".py", ".go", ".rs", ".php", ".rb", ".cs", ".cpp", ".hpp", ".h"];
  const out = [];
  for (const ext of extensions) out.push(base.endsWith(ext) ? base : `${base}${ext}`);
  for (const ext of extensions.filter(Boolean)) out.push(`${base}/index${ext}`);
  return out;
}

function normalizePath(path) {
  const parts = [];
  for (const part of path.split(/[\\/]/)) {
    if (!part || part === ".") continue;
    if (part === "..") parts.pop();
    else parts.push(part);
  }
  return parts.join("/");
}

function detectFrameworks() {
  const found = new Set();
  for (const file of ["package.json", "Cargo.toml", "pyproject.toml", "go.mod", "pom.xml", "build.gradle", "build.gradle.kts"]) {
    const path = join(projectRoot, file);
    if (!existsSync(path)) continue;
    const lower = readFileSync(path, "utf-8").toLowerCase();
    for (const [needle, name] of [
      ["react", "React"], ["vite", "Vite"], ["tauri", "Tauri"], ["next", "Next.js"],
      ["vue", "Vue"], ["fastapi", "FastAPI"], ["django", "Django"], ["flask", "Flask"],
      ["spring-boot", "Spring Boot"], ["springframework", "Spring"], ["gin-gonic", "Gin"],
      ["tokio", "Tokio"], ["serde", "Serde"], ["rails", "Rails"],
    ]) {
      if (lower.includes(needle)) found.add(name);
    }
  }
  return [...found].sort((a, b) => a.localeCompare(b));
}

function hasStructure(analysis) {
  return (analysis.functions?.length ?? 0) > 0 || (analysis.classes?.length ?? 0) > 0;
}

function hasNonCodeStructure(analysis) {
  return ["definitions", "services", "endpoints", "steps", "resources", "sections"]
    .some((key) => (analysis[key]?.length ?? 0) > 0);
}

function nodeTypeFor(file, language) {
  if (["yaml", "json", "toml", "xml", "env", "config"].includes(language)) return "config";
  if (["markdown"].includes(language)) return "document";
  if (["sql"].includes(language)) return "table";
  if (["graphql", "protobuf"].includes(language)) return "schema";
  if (["terraform"].includes(language)) return "resource";
  return "file";
}

function categoryFor(file, language) {
  if (file.includes("/test/") || file.includes("/tests/") || file.match(/\.(test|spec)\./)) return "test";
  if (["yaml", "json", "toml", "xml", "env", "config"].includes(language)) return "config";
  if (["markdown"].includes(language)) return "docs";
  return "code";
}

function sourceRank(file) {
  if (file.startsWith("src/")) return 0;
  if (file.startsWith("app/") || file.startsWith("apps/") || file.startsWith("crates/")) return 1;
  if (file.startsWith(".")) return 9;
  return 5;
}

function isKnownPlainFile(name) {
  return ["Dockerfile", "Makefile", "CMakeLists.txt"].includes(name);
}

function isBinaryLike(name) {
  return [".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf", ".zip", ".tar", ".gz", ".woff", ".woff2", ".ttf", ".exe", ".dll", ".class", ".jar"]
    .includes(extname(name).toLowerCase());
}

function toPosix(path) {
  return path.split(/[\\/]/).filter(Boolean).join("/");
}

function safe(fn) {
  try {
    return fn();
  } catch {
    return null;
  }
}
